While[!(FreeQ[pospint,lastint[n_,m_,p_]/;(p>0)]),pospint=pospint/.{lastint[n_,m_,p_]:>(p/(p+1)*lastint[n,m,p-1]+n/(p+1)*lastint[n-1,m,p-1]-n/(p+1)*lastint[n-1,m,p]-m/(p+1)*lastint[n,m-1,p])/;(p>0)};pospint=Expand[pospint];];
Return[Expand[pospint/.lastint[mmm_,nnn_,ppp_]:>HypExpU[mmm,nnn,ppp]]]
])


HypExpAtOne[A_List,B_List,\[Epsilon]_]:=(Module[{innput,aavektor,bbvektor,bbvektorkopie,aasumme,bbsumme,aasummeinteger,bbsummeinteger,unionbb,vielfachheit,pbzzaehler,pbznenner,pbzbruch,uniqueka,phaa,phbb,zerlegt,zerlegtpiece,kacoeff,kabruch,bbvergleich,kabruchpower,ult,kwq,fvt,hypterm,intermedPFQ,ultim,res,kiop,nochmalzwischen,kioopp},innput={A,B,1};
aavektor=Sort[Expand[innput[[1]]]];bbvektor=Sort[Expand[innput[[2]]]];
Do[bbvektorkopie[laeufer]=Expand[bbvektor],{laeufer,1,Length[bbvektor]}];
aasumme=Sum[aavektor[[jj]],{jj,1,Length[aavektor]}]//Expand;
bbsumme=Sum[bbvektor[[pp]],{pp,1,Length[bbvektor]}]//Expand;
aasummeinteger=Sum[((aavektor[[ii]])/.{\[Epsilon]:>0}),{ii,1,Length[aavektor]}]//Expand;
bbsummeinteger=Sum[((bbvektor[[uu]])/.{\[Epsilon]:>0}),{uu,1,Length[bbvektor]}]//Expand;
unionbb=Union[Expand[bbvektor]];
vielfachheit=Length[Cases[Expand[bbvektor],#]]&/@unionbb;
pbzzaehler=Product[(uniqueka+phaa[jkj]),{jkj,1,Length[aavektor]}];
pbznenner=Product[(uniqueka+phbb[ok])^(vielfachheit[[ok]]),{ok,1,Length[unionbb]}];
pbzbruch=pbzzaehler/pbznenner;
zerlegt=Apart[pbzbruch,uniqueka]-uniqueka+Expand[Sum[vielfachheit[[neph]]*phbb[neph],{neph,1,Length[unionbb]}]]-Expand[Sum[phaa[bvc],{bvc,1,Length[aavektor]}]];
Do[zerlegtpiece[ult]=zerlegt[[ult]];
kacoeff[ult]=zerlegtpiece[ult]/.{Power[uniqueka+phbb[asko_],pow_]:>1/;((IntegerQ[pow])&&(pow<=-1))};
kabruch[ult]=zerlegtpiece[ult]/kacoeff[ult]//Simplify;
bbvergleich[ult]=(kabruch[ult][[1]]-uniqueka)//Expand;
kabruchpower[ult]=-kabruch[ult][[2]];
bbvektorkopie[ult]=Flatten[Table[Table[phbb[kwq],{fvt,1,vielfachheit[[kwq]]}],{kwq,1,Length[unionbb]}]];
bbvektorkopie[ult]=DeleteCases[bbvektorkopie[ult],bbvergleich[ult]];
Do[bbvektorkopie[ult]=Append[bbvektorkopie[ult],bbvergleich[ult]+1],{kiop,1,kabruchpower[ult]}];
nochmalzwischen=Length[bbvektorkopie[ult]];
Do[bbvektorkopie[ult]=Append[bbvektorkopie[ult],bbvergleich[ult]],{kioopp,1,Length[bbvektor]-nochmalzwischen}];
Clear[nochmalzwischen];
hypterm[ult]=(((kacoeff[ult])/(bbvergleich[ult])^(kabruchpower[ult])*intermedPFQ[aavektor,bbvektorkopie[ult],1])/.{phaa[jmn_]:>aavektor[[jmn]],phbb[jjmmnn_]:>unionbb[[jjmmnn]]}),{ult,1,Length[zerlegt]}];
res=Collect[Sum[hypterm[ultim]/(bbsumme-aasumme),{ultim,1,Length[zerlegt]}],intermedPFQ[{nhy___},{tgb___},1],Simplify;Factor];
res=res/.intermedPFQ[AA_List,BB_List,1]:>HypExpAtOne[AA,BB,\[Epsilon]]/;((Apply[Plus,BB]-Apply[Plus,AA])/.\[Epsilon]->0)<=0;
Return[Collect[res/.intermedPFQ->HypergeometricPFQ,HypergeometricPFQ[_,_,_],Simplify;Factor]]])



HypExpAtOne[A_List,B_List,\[Epsilon]_,order_]:=Module [{res,rres,C},
res=HypExp`Private`HypExpAtOne[A,B,\[Epsilon]];
res=Collect[res,_HypergeometricPFQ,C];
res=res/.C[x_]:>C[x,Switch[rres=Series[x,{\[Epsilon],0,0}],_SeriesData,rres[[-3]],_,0]];
res=res/.{C[coeff_,n_] h_HypergeometricPFQ:>coeff Series[h,{\[Epsilon],0,Max[0,order-n]}],C[coeff_,n_]->coeff};
Return[Simplify[res]]
]


